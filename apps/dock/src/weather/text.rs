//! Weather-specific text, with the same resolved language as the Dock.
use muelle_config::Language;
use muelle_weather::Condition;
pub struct Text {
    pub conditions: [&'static str; 11],
    pub title: &'static str,
    pub loading: &'static str,
    pub location_needed: &'static str,
    pub unavailable: &'static str,
    pub current_location: &'static str,
    pub saved_location: &'static str,
    pub stale: &'static str,
    pub settings: &'static str,
}
pub fn text(language: Language) -> &'static Text {
    match language {
        Language::Es => &ES,
        Language::Fr => &FR,
        Language::Pt => &PT,
        Language::Zh => &ZH,
        Language::Hi => &HI,
        Language::Ar => &AR,
        Language::Bn => &BN,
        _ => &EN,
    }
}
