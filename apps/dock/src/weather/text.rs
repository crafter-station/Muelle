impl Text {
    pub fn condition(&self, condition: Condition) -> &'static str {
        self.conditions[match condition {
            Condition::Clear => 0,
            Condition::PartlyCloudy => 1,
            Condition::Overcast => 2,
            Condition::Fog => 3,
            Condition::Drizzle => 4,
            Condition::Rain => 5,
            Condition::FreezingRain => 6,
            Condition::Snow => 7,
            Condition::Showers => 8,
            Condition::Thunderstorm => 9,
            Condition::Unknown => 10,
        }]
    }
}
